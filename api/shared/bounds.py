"""Bounds files: the numbers `player-api` checks checkpoints against (spine S5.1 and S6, F §10.1; M1-23).

A bounds file is generated by web/game-core/scripts/build-bounds.ts from one ruleset and one planet document, and the
release publishes it create-only on the player site at

    game-data/bounds/<rulesetVersion>__<campaignVersion>.json

Python never interprets waves: it reads these numbers and nothing else. `load_bounds` fetches the file for a run's
pinned pair from the site bucket (`GAME_DATA_BUCKET`), checks its shape, and caches it for the life of the container
(files are immutable, so a cached copy can never go stale). A pair whose file is missing or malformed raises
`BoundsUnavailable`: the run is not playable (`CONTENT_VERSION_UNSUPPORTED`, spine S5.1), and nothing is cached, so a
later call retries.
"""

from __future__ import annotations

import json
import os
import re
from collections.abc import Mapping
from typing import Any

import boto3
from botocore.exceptions import ClientError

from shared.rules.contracts import LIMITS


def _anchored(pattern: str) -> re.Pattern[str]:
    # The limits file writes JSON Schema / JavaScript patterns ending in $; Python's $ also matches before a trailing
    # newline, so end with \Z instead.
    return re.compile(pattern.removesuffix("$") + r"\Z")


# Version strings are path segments joined by "__" (H.8.5). Both patterns and the G-15 limit come from
# contracts/limits.json, the same numbers web/game-core/src/data/game-data.ts checks against.
VERSION = _anchored(LIMITS["gameData"]["versionPattern"])
KEY_ID = _anchored(LIMITS["ids"]["keyId"])
TARGETING_MODES: frozenset[str] = frozenset(LIMITS["targeting"])
BUCKET_ENV = "GAME_DATA_BUCKET"
KEY_PREFIX = "game-data/bounds/"
MAX_TRANSACTION_ACTIONS: int = LIMITS["gameData"]["createRunMaxActions"]  # G-15: TransactWriteItems limit (spine S5.1)
MAX_FILE_BYTES = 256 * 1024  # a bounds file is a few KB; anything near this is not one

_TOP_KEYS = frozenset(
    {"kind", "rulesetVersion", "campaignVersion", "mechanics", "colony", "powerInventoryCap", "sell", "classes", "pads",
     "waveSets"}
)  # fmt: skip
_WAVE_SET_KEYS = frozenset(
    {"mode", "finalWave", "meteorAfter", "startCredits", "colonyHealth", "classes", "padsOpenAsForWave",
     "createRunActions", "maxBounty", "normalRewardByInterval"}
)  # fmt: skip

_cache: dict[tuple[str, str, str], dict[str, Any]] = {}


class BoundsUnavailable(Exception):
    """The bounds file for a (ruleset, campaign) pair cannot be loaded: missing, unreadable or malformed."""


def bounds_key(ruleset_version: str, campaign_version: str) -> str:
    """The object key of one pair's bounds file. Raises ValueError for a version that is not path-safe."""
    for name, value in (("rulesetVersion", ruleset_version), ("campaignVersion", campaign_version)):
        if not isinstance(value, str) or not VERSION.match(value):
            raise ValueError(f"{name} {value!r} does not match {LIMITS['gameData']['versionPattern']}")
    return f"{KEY_PREFIX}{ruleset_version}__{campaign_version}.json"


def _int(value: Any, where: str, minimum: int = 0) -> int:
    # bool is a subclass of int in Python; JSON true is never a number here (the same rule as shared.rules.schema).
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise BoundsUnavailable(f"{where} must be an integer >= {minimum}, got {value!r}")
    return value


def _ints(value: Any, where: str, minimum: int = 0) -> list[int]:
    if not isinstance(value, list):
        raise BoundsUnavailable(f"{where} must be a list")
    return [_int(v, f"{where}[{i}]", minimum) for i, v in enumerate(value)]


def _obj(value: Any, where: str, keys: frozenset[str] | None = None) -> Mapping[str, Any]:
    if not isinstance(value, dict):
        raise BoundsUnavailable(f"{where} must be an object")
    if keys is not None and set(value) != keys:
        raise BoundsUnavailable(f"{where} keys {sorted(value)} are not {sorted(keys)}")
    return value


def parse_bounds(data: Any, ruleset_version: str, campaign_version: str) -> dict[str, Any]:
    """Check a decoded bounds file for the given pair and return it. Raises BoundsUnavailable on any problem."""
    top = _obj(data, "bounds")
    if not _TOP_KEYS <= set(top) <= {*_TOP_KEYS, "powerAwardRotation"}:
        raise BoundsUnavailable(f"bounds keys {sorted(top)} are not {sorted(_TOP_KEYS)} (+ powerAwardRotation)")
    rotation = top.get("powerAwardRotation", [])
    if not isinstance(rotation, list) or not all(isinstance(p, str) and KEY_ID.match(p) for p in rotation):
        raise BoundsUnavailable("bounds.powerAwardRotation must be a list of power IDs (Phase 51)")
    if top["kind"] != "bounds":
        raise BoundsUnavailable(f"bounds.kind is {top['kind']!r}, expected 'bounds'")
    if (top["rulesetVersion"], top["campaignVersion"]) != (ruleset_version, campaign_version):
        raise BoundsUnavailable(
            f"the file is for {top['rulesetVersion']!r} + {top['campaignVersion']!r}, "
            f"not {ruleset_version!r} + {campaign_version!r}"
        )
    _int(top["mechanics"], "bounds.mechanics", 1)
    _int(top["powerInventoryCap"], "bounds.powerInventoryCap")
    colony = _obj(top["colony"], "bounds.colony", frozenset({"maxHealth", "shieldCap"}))
    _int(colony["maxHealth"], "bounds.colony.maxHealth", 1)
    _int(colony["shieldCap"], "bounds.colony.shieldCap")
    sell = _obj(top["sell"], "bounds.sell", frozenset({"refundPct", "roundDownTo"}))
    if _int(sell["refundPct"], "bounds.sell.refundPct") > 100:
        raise BoundsUnavailable("bounds.sell.refundPct must be at most 100")
    _int(sell["roundDownTo"], "bounds.sell.roundDownTo", 1)

    classes = _obj(top["classes"], "bounds.classes")
    for class_id, entry in classes.items():
        where = f"bounds.classes.{class_id}"
        if not KEY_ID.match(class_id):
            raise BoundsUnavailable(f"{where}: not a key ID")
        cls = _obj(entry, where)
        required = {"unlockAfterWave", "deployCap", "targeting", "levelCosts", "cumulativeCosts"}
        if not required <= set(cls) <= {*required, "targetingFromLevel"}:
            raise BoundsUnavailable(f"{where} keys {sorted(cls)} are not {sorted(required)} (+ targetingFromLevel)")
        _int(cls["unlockAfterWave"], f"{where}.unlockAfterWave")
        if cls["deployCap"] is not None:
            _int(cls["deployCap"], f"{where}.deployCap", 1)
        targeting = cls["targeting"]
        if (
            not isinstance(targeting, list)
            or not targeting
            or not all(isinstance(t, str) and t in TARGETING_MODES for t in targeting)
            or len(set(targeting)) != len(targeting)
        ):
            raise BoundsUnavailable(f"{where}.targeting must be a non-empty list of distinct targeting modes")
        # Phase 30: the level each level-gated mode opens at (only modes above level 1; absent when there are none).
        gated = _obj(cls.get("targetingFromLevel", {}), f"{where}.targetingFromLevel")
        for mode, level in gated.items():
            if mode not in targeting:
                raise BoundsUnavailable(f"{where}.targetingFromLevel: {mode!r} is not one of the class's modes")
            _int(level, f"{where}.targetingFromLevel.{mode}", 2)
        costs = _ints(cls["levelCosts"], f"{where}.levelCosts", 1)
        running = [sum(costs[: i + 1]) for i in range(len(costs))]
        if not costs or _ints(cls["cumulativeCosts"], f"{where}.cumulativeCosts", 1) != running:
            raise BoundsUnavailable(f"{where}: cumulativeCosts must be the running sum of levelCosts")

    pads = _obj(top["pads"], "bounds.pads")
    for pad_id, entry in pads.items():
        if not KEY_ID.match(pad_id):
            raise BoundsUnavailable(f"bounds.pads.{pad_id}: not a key ID")
        pad = _obj(entry, f"bounds.pads.{pad_id}", frozenset({"opensAfterWave"}))
        _int(pad["opensAfterWave"], f"bounds.pads.{pad_id}.opensAfterWave")

    wave_sets = _obj(top["waveSets"], "bounds.waveSets")
    if not wave_sets:
        raise BoundsUnavailable("bounds.waveSets is empty")
    for set_id, entry in wave_sets.items():
        where = f"bounds.waveSets.{set_id}"
        if not KEY_ID.match(set_id):
            raise BoundsUnavailable(f"{where}: not a key ID")
        ws = _obj(entry, where)
        if not _WAVE_SET_KEYS <= set(ws) <= {*_WAVE_SET_KEYS, "endless"}:
            raise BoundsUnavailable(f"{where} keys {sorted(ws)} are not {sorted(_WAVE_SET_KEYS)} (+ endless)")
        if "endless" in ws:  # Phase 54: endless maxBounty from wave finalWave + 1, and the endless learning reward
            endless = _obj(ws["endless"], f"{where}.endless", frozenset({"maxBounty", "learningReward"}))
            _ints(endless["maxBounty"], f"{where}.endless.maxBounty")
            _int(endless["learningReward"], f"{where}.endless.learningReward")
        if ws["mode"] not in ("CAMPAIGN", "CHALLENGE"):
            raise BoundsUnavailable(f"{where}.mode is {ws['mode']!r}")
        final_wave = _int(ws["finalWave"], f"{where}.finalWave", 1)
        meteor_after = _ints(ws["meteorAfter"], f"{where}.meteorAfter", 1)
        for name in ("startCredits", "colonyHealth", "padsOpenAsForWave"):
            _int(ws[name], f"{where}.{name}")
        if not isinstance(ws["classes"], list) or not all(isinstance(c, str) and c in classes for c in ws["classes"]):
            raise BoundsUnavailable(f"{where}.classes must name classes in this file")
        if len(_ints(ws["maxBounty"], f"{where}.maxBounty")) != final_wave:
            raise BoundsUnavailable(f"{where}.maxBounty must have finalWave ({final_wave}) entries")
        if len(_ints(ws["normalRewardByInterval"], f"{where}.normalRewardByInterval")) != final_wave - 1:
            raise BoundsUnavailable(f"{where}.normalRewardByInterval must have finalWave - 1 entries")
        actions = 3 + (final_wave - 1) + len(meteor_after)
        if _int(ws["createRunActions"], f"{where}.createRunActions") != actions or actions > MAX_TRANSACTION_ACTIONS:
            raise BoundsUnavailable(f"{where}.createRunActions must be {actions} and at most {MAX_TRANSACTION_ACTIONS}")
    return dict(top)


def load_bounds(
    ruleset_version: str,
    campaign_version: str,
    *,
    bucket: str | None = None,
    s3: Any = None,
) -> dict[str, Any]:
    """The bounds file for a run's pinned (rulesetVersion, campaignVersion), from the player site bucket.

    `bucket` defaults to the GAME_DATA_BUCKET environment variable and `s3` to a boto3 client; tests pass either.
    Cached per container on success. Treat the result as read-only: every caller shares it.
    """
    key = bounds_key(ruleset_version, campaign_version)
    bucket = bucket or os.environ.get(BUCKET_ENV, "")
    if not bucket:
        raise BoundsUnavailable(f"no bucket: set {BUCKET_ENV}")
    cache_key = (bucket, ruleset_version, campaign_version)
    cached = _cache.get(cache_key)
    if cached is not None:
        return cached

    client = s3 if s3 is not None else boto3.client("s3")
    try:
        response = client.get_object(Bucket=bucket, Key=key)
        body = response["Body"].read(MAX_FILE_BYTES + 1)
    except ClientError as exc:
        code = exc.response.get("Error", {}).get("Code", "")
        raise BoundsUnavailable(f"s3://{bucket}/{key}: {code or exc}") from exc
    if len(body) > MAX_FILE_BYTES:
        raise BoundsUnavailable(f"s3://{bucket}/{key} is larger than {MAX_FILE_BYTES} bytes")
    try:
        data = json.loads(body)
    except ValueError as exc:  # JSONDecodeError and UnicodeDecodeError are both ValueErrors
        raise BoundsUnavailable(f"s3://{bucket}/{key} is not JSON: {exc}") from exc
    bounds = parse_bounds(data, ruleset_version, campaign_version)
    _cache[cache_key] = bounds
    return bounds


def clear_cache() -> None:
    """Forget every cached file (tests only: a real container never needs to)."""
    _cache.clear()
