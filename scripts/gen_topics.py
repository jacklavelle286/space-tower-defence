#!/usr/bin/env python3
"""Generate the topic registry, contracts/topics.json, from the C19 topic tables of the plan.

Source: docs/plan/C-game-and-learning-design.md, section C19: tables C19.1 to C19.9 (ages 5 to 7, which are the bands of
Reception, Year 1 and Year 2) and, from YG2, C19.11 onwards ("Band 8 (Year 3)" and up; ADR-0056). One per band and
subject.
C19 says the registry (topic ID, subject, bands, curriculum references) is one versioned JSON file shipped to both apps
and both API Lambdas. Python reads it directly (api/shared/topics.py); TypeScript gets it through
web/game-core/scripts/gen-contracts.ts (web/shared/src/topics.ts).

How each row becomes a topic:
  topicId      the first column, without the "(5-6)" / "(6-7)" marker (written with an en dash in C19)
  subject      the table's subject (maths, phonics, spelling, grammar)
  title        a short admin label made mechanically from the topicId (see title_from_id)
  description  "What the child does"
  ages         the table's band, plus the neighbouring band when the row is marked "(5-6)", "(8-9)" and so on
  curriculum   "Curriculum reference" split on ";" and trimmed, each segment kept exactly as written
  types        "Types" split on ","
  audio        "Audio", as written
A topic that appears in more than one table is one entry: ages are the union; description and audio come from the
first table it appears in; curriculum and types are the union in order of first appearance.

Order: subject, then first age, then the order the topic first appears in C19.

Usage (from the repository root):
  python3 scripts/gen_topics.py           write contracts/topics.json
  python3 scripts/gen_topics.py --check   exit 1 if contracts/topics.json is not what the generator would write

Standard library only; runs on Python 3.12 and 3.14.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "docs" / "plan" / "C-game-and-learning-design.md"
OUTPUT = REPO / "contracts" / "topics.json"
VERSION = 1
SUBJECTS = ("maths", "phonics", "spelling", "grammar")
TOPIC_ID = re.compile(r"[a-z0-9-]{1,40}")
TITLE_MAX = 60
TYPES = frozenset({"PS", "NS", "OM", "AR", "MC", "TY"})
COLUMNS = ("topicId", "What the child does", "Curriculum reference", "Types", "Audio", "Source", "Example")

_HEADING = re.compile(
    r"^### C19\.(\d+) (?:Age ([5-7])|Band (8|9|10|11) \(Year ([3-6])\)) — (maths|phonics|spelling|grammar) \((\d+) topics?\)$"
)
_ANY_HEADING = re.compile(r"^#{1,3} ")
EN_DASH = "\u2013"  # C19 writes the shared-band marker as "(5<en dash>6)"
_ID_CELL = re.compile(r"^`([^`]+)`(?: \((\d{1,2})" + EN_DASH + r"(\d{1,2})\))?$")
# Tokens kept as written in titles (upper case); every other token is lower case with letters and digits split.
_TITLE_TOKENS = {"2d": "2D", "3d": "3D", "y1": "Y1", "y2": "Y2", "y3": "Y3", "y4": "Y4", "y5": "Y5", "y6": "Y6",
                 "cvc": "CVC", "gpc": "GPC"}  # fmt: skip

COMMENT = (
    "GENERATED by scripts/gen_topics.py from docs/plan/C-game-and-learning-design.md section C19 (tables C19.1-C19.9 "
    "and C19.11 onwards). "
    "Do not edit by hand: change C19 and run `python3 scripts/gen_topics.py`. The topic registry: topic IDs are "
    "append-only, never renamed or reused (C19). Read by api/shared/topics.py and, through "
    "web/game-core/scripts/gen-contracts.ts, by web/shared/src/topics.ts. A topic in two tables is one entry: ages "
    "and curriculum and types are the union; description and audio come from its first table."
)


class SourceError(Exception):
    """C19 is not in the shape the generator understands."""


def title_from_id(topic_id: str, subject: str) -> str:
    """A readable, deterministic admin label: 'maths-count-objects-to10' -> 'Count objects to 10'."""
    words: list[str] = []
    for token in topic_id.removeprefix(f"{subject}-").split("-"):
        if token in _TITLE_TOKENS:
            words.append(_TITLE_TOKENS[token])
        elif words and words[-1] == "set" and len(token) == 1:
            words.append(token.upper())  # "set-a" -> "set A"
        else:
            words.extend(re.findall(r"[a-z]+|[0-9]+", token))  # "to10" -> "to 10", "phase5" -> "phase 5"
    # A run of numbers is a list: "steps-2-5-10" -> "steps 2, 5, 10".
    title = " ".join(words)
    title = re.sub(r"(?<=\d) (?=\d)", ", ", title)
    return title[:1].upper() + title[1:]


def _cells(line: str) -> list[str]:
    if not (line.startswith("|") and line.endswith("|")):
        raise SourceError(f"not a table row: {line!r}")
    return [cell.strip() for cell in line[1:-1].split("|")]


def parse_tables(text: str) -> list[dict[str, Any]]:
    """Every C19.1-C19.9 row, in document order, as {topicId, subject, band, ages, description, ...}."""
    rows: list[dict[str, Any]] = []
    tables: list[int] = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        match = _HEADING.match(lines[i])
        i += 1
        if not match:
            continue
        number, subject, expected = int(match[1]), match[5], int(match[6])
        band = int(match[2]) if match[2] else int(match[3])
        if match[3] and int(match[4]) != band - 5:
            raise SourceError(f"C19.{number}: band {band} is Year {band - 5}, not Year {match[4]}")
        tables.append(number)
        found = 0
        while i < len(lines) and not _ANY_HEADING.match(lines[i]):
            line = lines[i].strip()
            i += 1
            if not line.startswith("|"):
                continue
            cells = _cells(line)
            if tuple(cells) == COLUMNS or set("".join(cells)) <= set("-"):
                continue  # header or separator
            if len(cells) != len(COLUMNS):
                raise SourceError(f"C19.{number}: expected {len(COLUMNS)} columns: {line!r}")
            id_match = _ID_CELL.match(cells[0])
            if not id_match:
                raise SourceError(f"C19.{number}: bad topicId cell {cells[0]!r}")
            topic_id = id_match[1]
            if not TOPIC_ID.fullmatch(topic_id) or not topic_id.startswith(f"{subject}-"):
                raise SourceError(f"C19.{number}: bad topicId {topic_id!r}")
            ages = {band}
            if id_match[2]:
                low, high = int(id_match[2]), int(id_match[3])
                if high != low + 1 or band not in (low, high):
                    raise SourceError(f"C19.{number}: {topic_id}: marker ({low}-{high}) does not fit age {band}")
                ages |= {low, high}
            types = [t.strip() for t in cells[3].split(",")]
            if not types or any(t not in TYPES for t in types):
                raise SourceError(f"C19.{number}: {topic_id}: unknown type in {cells[3]!r}")
            curriculum = [part.strip() for part in cells[2].split(";") if part.strip()]
            if not curriculum or not cells[1] or not cells[4]:
                raise SourceError(f"C19.{number}: {topic_id}: empty description, curriculum or audio")
            rows.append(
                {
                    "topicId": topic_id,
                    "subject": subject,
                    "ages": ages,
                    "description": cells[1],
                    "curriculum": curriculum,
                    "types": types,
                    "audio": cells[4],
                }
            )
            found += 1
        if found != expected:
            raise SourceError(f"C19.{number}: heading says {expected} topics, table has {found}")
    if tables[:9] != list(range(1, 10)) or tables[9:] != list(range(11, 11 + len(tables) - 9)):
        raise SourceError(f"expected tables C19.1-C19.9, then C19.11 onwards, in order; found {tables}")
    return rows


def _union(first: list[str], more: list[str]) -> list[str]:
    return first + [item for item in more if item not in first]


def build_registry(text: str) -> dict[str, Any]:
    merged: dict[str, dict[str, Any]] = {}
    first_seen: dict[str, int] = {}
    for index, row in enumerate(parse_tables(text)):
        topic_id = row["topicId"]
        if topic_id not in merged:
            merged[topic_id] = row
            first_seen[topic_id] = index
            continue
        topic = merged[topic_id]
        if topic["subject"] != row["subject"]:
            raise SourceError(f"{topic_id}: appears under two subjects")
        topic["ages"] = topic["ages"] | row["ages"]
        topic["curriculum"] = _union(topic["curriculum"], row["curriculum"])
        topic["types"] = _union(topic["types"], row["types"])
    topics = []
    for topic_id, row in merged.items():
        ages = sorted(row["ages"])
        if ages != list(range(ages[0], ages[-1] + 1)):
            raise SourceError(f"{topic_id}: ages {ages} are not one range")
        title = title_from_id(topic_id, row["subject"])
        if len(title) > TITLE_MAX:
            raise SourceError(f"{topic_id}: title longer than {TITLE_MAX} characters")
        topics.append(
            {
                "topicId": topic_id,
                "subject": row["subject"],
                "title": title,
                "description": row["description"],
                "ages": ages,
                "curriculum": row["curriculum"],
                "types": row["types"],
                "audio": row["audio"],
            }
        )
    topics.sort(key=lambda t: (SUBJECTS.index(t["subject"]), t["ages"][0], first_seen[t["topicId"]]))
    return {"$comment": COMMENT, "version": VERSION, "topics": topics}


def render(registry: dict[str, Any]) -> str:
    return json.dumps(registry, ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if contracts/topics.json is out of date")
    args = parser.parse_args(argv)
    try:
        content = render(build_registry(SOURCE.read_text(encoding="utf-8")))
    except SourceError as error:
        print(f"gen_topics: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != content:
            print("gen_topics: contracts/topics.json is stale; run python3 scripts/gen_topics.py", file=sys.stderr)
            return 1
        print("gen_topics: contracts/topics.json is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"gen_topics: wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
