// Generates TypeScript from the shared contracts, so the types are never written twice (Phase 11, M1-12).
//
//   contracts/schemas/*.schema.json + contracts/limits.json
//     -> web/game-core/src/rules/contracts.generated.ts  (types, the schemas as data for the validator, LIMITS)
//     -> web/shared/src/limits.ts                        (LIMITS for the apps)
//   contracts/topics.json (itself generated from plan C19 by scripts/gen_topics.py)
//     -> web/shared/src/topics.ts                        (TOPICS and topicById for the apps)
//
// Run from web/:   node game-core/scripts/gen-contracts.ts          (write)
//                  node game-core/scripts/gen-contracts.ts --check  (exit 1 if a generated file is out of date)
// `npm test` also fails when a generated file is stale (src/rules/contracts.generated.test.ts).
//
// The generator understands a deliberately small part of JSON Schema (the SUPPORTED keywords below) and refuses
// anything else, so the TypeScript validator (src/rules/schema.ts) and the Python mirror only need that same part.
// It imports only node: modules so Node 24 can run it directly (type stripping).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const REPO = resolve(import.meta.dirname, "..", "..", "..");
const SCHEMA_DIR = join(REPO, "contracts", "schemas");
const LIMITS_FILE = join(REPO, "contracts", "limits.json");
const GAME_CORE_OUT = join(REPO, "web", "game-core", "src", "rules", "contracts.generated.ts");
const SHARED_OUT = join(REPO, "web", "shared", "src", "limits.ts");
const TOPICS_FILE = join(REPO, "contracts", "topics.json");
const TOPICS_OUT = join(REPO, "web", "shared", "src", "topics.ts");

/** Keywords the validator implements. Annotations are allowed and ignored. */
export const SUPPORTED_KEYWORDS: readonly string[] = [
  "$ref",
  "type",
  "const",
  "enum",
  "pattern",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "properties",
  "required",
  "additionalProperties",
  "propertyNames",
  "items",
  "minItems",
  "maxItems",
  "allOf",
  "if",
  "then",
];
const ANNOTATIONS: readonly string[] = ["$schema", "$id", "$defs", "$comment", "title", "description"];

const HEADER = (source: string): string =>
  `// GENERATED by web/game-core/scripts/gen-contracts.ts from ${source}. Do not edit by hand:\n` +
  "// change the contract and run `node game-core/scripts/gen-contracts.ts` in web/.\n";

function isObject(value: Json | undefined): value is JsonObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function readJson(path: string): Json {
  return JSON.parse(readFileSync(path, "utf8")) as Json;
}

export function loadSchemas(): Map<string, JsonObject> {
  const schemas = new Map<string, JsonObject>();
  for (const name of readdirSync(SCHEMA_DIR).filter((n) => n.endsWith(".schema.json")).sort()) {
    const schema = readJson(join(SCHEMA_DIR, name));
    if (!isObject(schema) || schema["$id"] !== name) throw new Error(`${name}: $id must equal the file name`);
    checkKeywords(schema, name);
    schemas.set(name, schema);
  }
  return schemas;
}

/** Walk every subschema and refuse keywords outside the supported set. */
function checkKeywords(schema: JsonObject, where: string): void {
  for (const [key, value] of Object.entries(schema)) {
    if (!SUPPORTED_KEYWORDS.includes(key) && !ANNOTATIONS.includes(key)) {
      throw new Error(`${where}: unsupported JSON Schema keyword "${key}"`);
    }
    if (key === "properties" || key === "$defs") {
      if (!isObject(value)) throw new Error(`${where}/${key}: must be an object`);
      for (const [name, sub] of Object.entries(value)) {
        if (!isObject(sub)) throw new Error(`${where}/${key}/${name}: must be a schema object`);
        checkKeywords(sub, `${where}/${key}/${name}`);
      }
    } else if (key === "allOf") {
      if (!Array.isArray(value)) throw new Error(`${where}/allOf: must be an array`);
      value.forEach((sub, i) => {
        if (!isObject(sub)) throw new Error(`${where}/allOf/${i}: must be a schema object`);
        checkKeywords(sub, `${where}/allOf/${i}`);
      });
    } else if (["items", "propertyNames", "if", "then"].includes(key) || (key === "additionalProperties" && isObject(value))) {
      if (!isObject(value)) throw new Error(`${where}/${key}: must be a schema object`);
      checkKeywords(value, `${where}/${key}`);
    }
  }
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

class TypeWriter {
  private readonly names = new Map<string, string>(); // "file#/$defs/x" or "file#" -> type name
  private readonly schemas: Map<string, JsonObject>;
  constructor(schemas: Map<string, JsonObject>) {
    this.schemas = schemas;
    const taken = new Set<string>();
    const claim = (key: string, name: string): void => {
      if (taken.has(name)) throw new Error(`two schemas generate the type name ${name}`);
      taken.add(name);
      this.names.set(key, name);
    };
    for (const [id, schema] of schemas) {
      if (schema["type"] !== undefined) {
        const title = schema["title"];
        if (typeof title !== "string") throw new Error(`${id}: a typed root schema needs a title`);
        claim(`${id}#`, title);
      }
      const defs = schema["$defs"];
      if (isObject(defs)) for (const def of Object.keys(defs)) claim(`${id}#/$defs/${def}`, pascal(def));
    }
  }

  private refName(ref: string, baseId: string): string {
    const [file = "", pointer = ""] = ref.split("#");
    const key = `${file === "" ? baseId : file}#${pointer}`;
    const name = this.names.get(key);
    if (name === undefined) throw new Error(`${baseId}: cannot resolve $ref ${ref}`);
    return name;
  }

  type(schema: JsonObject, baseId: string, indent: string): string {
    const ref = schema["$ref"];
    if (typeof ref === "string") return this.refName(ref, baseId);
    if (schema["const"] !== undefined) return JSON.stringify(schema["const"]);
    const enumValues = schema["enum"];
    if (Array.isArray(enumValues)) return enumValues.map((v) => JSON.stringify(v)).join(" | ");
    const type = schema["type"];
    if (Array.isArray(type)) return type.map((t) => this.type({ ...schema, type: t }, baseId, indent)).join(" | ");
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const items = schema["items"];
        if (!isObject(items)) throw new Error(`${baseId}: arrays need items`);
        const inner = this.type(items, baseId, indent);
        return `readonly ${inner.includes(" ") ? `(${inner})` : inner}[]`;
      }
      case "object":
        return this.objectType(schema, baseId, indent);
      default:
        throw new Error(`${baseId}: cannot make a type from ${JSON.stringify(schema)}`);
    }
  }

  private objectType(schema: JsonObject, baseId: string, indent: string): string {
    const properties = isObject(schema["properties"]) ? schema["properties"] : {};
    const allOf = schema["allOf"];
    if (Array.isArray(allOf)) return this.branchUnion(schema, properties, allOf, baseId, indent);
    const additional = schema["additionalProperties"];
    if (Object.keys(properties).length === 0) {
      if (additional === false) return "Readonly<Record<string, never>>";
      if (isObject(additional)) return `{ readonly [key: string]: ${this.type(additional, baseId, indent)} }`;
      return "Readonly<Record<string, unknown>>";
    }
    if (additional !== false) throw new Error(`${baseId}: objects with properties must set additionalProperties: false`);
    return this.literal(properties, this.required(schema), baseId, indent);
  }

  private required(schema: JsonObject): string[] {
    const required = schema["required"];
    return Array.isArray(required) ? required.filter((r): r is string => typeof r === "string") : [];
  }

  private literal(properties: JsonObject, required: string[], baseId: string, indent: string): string {
    const inner = `${indent}  `;
    const lines = Object.entries(properties).map(([name, sub]) => {
      if (!isObject(sub)) throw new Error(`${baseId}: property ${name} must be a schema`);
      const doc = typeof sub["description"] === "string" ? `${inner}/** ${sub["description"]} */\n` : "";
      const optional = required.includes(name) ? "" : "?";
      return `${doc}${inner}readonly ${name}${optional}: ${this.type(sub, baseId, inner)};`;
    });
    return `{\n${lines.join("\n")}\n${indent}}`;
  }

  /** `allOf: [{if: {properties: {k: {const}}}, then: {properties: {...}}}]` becomes a discriminated union. */
  private branchUnion(schema: JsonObject, base: JsonObject, allOf: Json[], baseId: string, indent: string): string {
    const variants = allOf.map((branch) => {
      const condition = isObject(branch) && isObject(branch["if"]) ? branch["if"]["properties"] : undefined;
      const outcome = isObject(branch) && isObject(branch["then"]) ? branch["then"]["properties"] : undefined;
      if (!isObject(condition) || !isObject(outcome)) throw new Error(`${baseId}: allOf supports only if/then branches`);
      const properties: JsonObject = { ...base };
      for (const [name, sub] of Object.entries(condition)) {
        if (!isObject(sub) || sub["const"] === undefined) throw new Error(`${baseId}: an if branch must test const values`);
        properties[name] = { const: sub["const"] };
      }
      Object.assign(properties, outcome);
      return this.literal(properties, this.required(schema), baseId, `${indent}  `);
    });
    return `\n${variants.map((v) => `${indent}  | ${v}`).join("\n")}`;
  }

  declarations(): string {
    const out: string[] = [];
    for (const [id, schema] of this.schemas) {
      const emit = (name: string, sub: JsonObject): void => {
        const doc = typeof sub["description"] === "string" ? `/** ${sub["description"]} */\n` : "";
        const body = this.type(sub, id, "");
        out.push(`${doc}export type ${name} =${body.startsWith("\n") ? "" : " "}${body};\n`);
      };
      if (schema["type"] !== undefined) emit(this.refName("#", id), schema);
      const defs = schema["$defs"];
      if (isObject(defs)) {
        for (const [def, sub] of Object.entries(defs)) if (isObject(sub)) emit(pascal(def), sub);
      }
    }
    return out.join("\n");
  }
}

function limitsLiteral(): string {
  const limits = readJson(LIMITS_FILE);
  if (!isObject(limits)) throw new Error("contracts/limits.json must be an object");
  const { $comment: _comment, ...rest } = limits;
  return `export const LIMITS = ${JSON.stringify(rest, null, 2)} as const;\n\nexport type Limits = typeof LIMITS;\n`;
}

const TOPIC_KEYS = ["topicId", "subject", "title", "description", "ages", "curriculum", "types", "audio"] as const;

function topicsModule(): string {
  const doc = readJson(TOPICS_FILE);
  if (!isObject(doc) || typeof doc["version"] !== "number" || !Array.isArray(doc["topics"])) {
    throw new Error("contracts/topics.json must be an object with a version and a topics array");
  }
  for (const topic of doc["topics"]) {
    if (!isObject(topic) || Object.keys(topic).join() !== TOPIC_KEYS.join()) {
      throw new Error(`contracts/topics.json: every topic must have exactly the keys ${TOPIC_KEYS.join(", ")}`);
    }
  }
  return (
    `${HEADER("contracts/topics.json")}` +
    "// The topic registry (plan C19), for the player and admin apps. contracts/topics.json is itself generated from\n" +
    "// plan C19 by scripts/gen_topics.py. Topic IDs are append-only: never renamed, never reused.\n\n" +
    "/** One registry entry. `curriculum` holds the C19 references as written; `types` are C20 abbreviations. */\n" +
    "export interface Topic {\n" +
    "  readonly topicId: string;\n" +
    '  readonly subject: "maths" | "phonics" | "spelling";\n' +
    "  readonly title: string;\n" +
    "  readonly description: string;\n" +
    "  readonly ages: readonly number[];\n" +
    "  readonly curriculum: readonly string[];\n" +
    "  readonly types: readonly string[];\n" +
    "  readonly audio: string;\n" +
    "}\n\n" +
    `export const TOPICS_VERSION = ${JSON.stringify(doc["version"])};\n\n` +
    "/** Every topic, in registry order (subject, first age, C19 order). */\n" +
    `export const TOPICS: readonly Topic[] = ${JSON.stringify(doc["topics"], null, 2)};\n\n` +
    "const BY_ID: ReadonlyMap<string, Topic> = new Map(TOPICS.map((topic) => [topic.topicId, topic]));\n\n" +
    "/** The registry entry for a topic ID, or undefined when it is not registered. */\n" +
    "export function topicById(topicId: string): Topic | undefined {\n" +
    "  return BY_ID.get(topicId);\n" +
    "}\n"
  );
}

/** Every generated file and its content. Pure apart from reading the contracts. */
export function generate(): Map<string, string> {
  const schemas = loadSchemas();
  const writer = new TypeWriter(schemas);
  const schemaData = Object.fromEntries(schemas);
  const gameCore =
    `${HEADER("contracts/schemas/*.schema.json and contracts/limits.json")}\n` +
    `${limitsLiteral()}\n` +
    "/** The contract schemas as data, keyed by $id, for the validator in schema.ts. */\n" +
    `export const SCHEMAS: Readonly<Record<string, unknown>> = ${JSON.stringify(schemaData, null, 2)};\n\n` +
    writer.declarations();
  const shared = `${HEADER("contracts/limits.json")}// The one shared limits file (spine S9.5), for the player and admin apps.\n\n${limitsLiteral()}`;
  return new Map([
    [GAME_CORE_OUT, gameCore],
    [SHARED_OUT, shared],
    [TOPICS_OUT, topicsModule()],
  ]);
}

/** Paths (relative to the repository) whose content on disk differs from what generate() produces. */
export function staleFiles(): string[] {
  const stale: string[] = [];
  for (const [path, content] of generate()) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = "";
    }
    if (current !== content) stale.push(path.slice(REPO.length + 1));
  }
  return stale;
}

if (argv[1] !== undefined && resolve(argv[1]) === fileURLToPath(import.meta.url)) {
  if (argv.includes("--check")) {
    const stale = staleFiles();
    if (stale.length > 0) {
      console.error(`Out of date (run node game-core/scripts/gen-contracts.ts in web/): ${stale.join(", ")}`);
      exit(1);
    }
    console.log("contracts: generated files are up to date");
  } else {
    for (const [path, content] of generate()) writeFileSync(path, content);
    console.log("contracts: generated files written");
  }
}
